    print("Patching SQLite text.db for DN 17 Bhāṇavāra 1 (paras 662..710)...")
    for idx, d in DN17_BHANAVARA_1.items():
        cur.execute("""
            INSERT INTO translation (book_id, para_idx, lang, title, text, verse, source, translator, conf)
            VALUES (6, ?, 'hi', ?, ?, ?, 'vri', 'VRI Team', 1.0)
            ON CONFLICT(book_id, para_idx, lang) DO UPDATE SET
                title=excluded.title,
                text=excluded.text,
                verse=excluded.verse,
                source=excluded.source,
                translator=excluded.translator,
                conf=1.0
        """, (idx, d["title"], d["text"], d["verse"]))
    conn.commit()
