def main():
    repo_dir = os.getcwd()
    output_file = os.path.join(repo_dir, "data/translations/hi/s0101t.jsonl")

    existing = []
    if os.path.exists(output_file):
        with open(output_file, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    existing.append(json.loads(line))

    data_map = {item["para"]: item for item in existing}
    print(f"Existing records in s0101t.jsonl: {len(data_map)}")

    for para_idx, text in batch3:
        record = {
            "book": BOOK_ID,
            "para": para_idx,
            "text": text,
            "id": f"{BOOK_ID}-{para_idx}-hi",
            "book_id": BOOK_ID,
            "para_idx": para_idx
        }
        data_map[para_idx] = record

    sorted_records = [data_map[p] for p in sorted(data_map.keys())]

    with open(output_file, "w", encoding="utf-8") as f:
        for r in sorted_records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"Updated s0101t.jsonl! Total records now: {len(sorted_records)}")
    print(f"Range: {sorted_records[0]['para']} to {sorted_records[-1]['para']}")

    paras = set(data_map.keys())
    min_p, max_p = min(paras), max(paras)
    missing = [p for p in range(min_p, max_p + 1) if p not in paras]
    if missing:
        print(f"WARNING: Missing paras in range: {missing[:20]}")
    else:
        print(f"SUCCESS: Continuous range {min_p} to {max_p} with 0 gaps!")

if __name__ == "__main__":
    main()
