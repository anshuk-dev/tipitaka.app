def patch_sqlite():
    db_path = 'db/text.db'
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    print("Patching SQLite text.db for DN 18 (paras 736..805)...")
    for idx, d in DN18_TRANSLATIONS.items():
        cur.execute("""
            INSERT INTO translation (book_id, para_idx, lang, title, text, verse, source, translator, conf)
            VALUES (6, ?, 'hi', ?, ?, ?, 'vri', 'VRI Team', 1.0)
            ON CONFLICT(book_id, para_idx, lang) DO UPDATE SET
                title=excluded.title,
                text=excluded.text,
                verse=excluded.verse,
                source=excluded.source,
                translator=excluded.translator,
                conf=1.0
        """, (idx, d["title"], d["text"], d["verse"]))
    conn.commit()
    conn.close()
    print("SQLite patch committed.")

def patch_jsonl():
    jsonl_path = 'data/translations/hi/s0102m.jsonl'
    lines = []
    with open(jsonl_path, 'r', encoding='utf-8') as f:
        for line in f:
            lines.append(json.loads(line))
    
    print(f"Read {len(lines)} lines from {jsonl_path}")
    count = 0
    for row in lines:
        p_idx = row['para_idx']
        if p_idx in DN18_TRANSLATIONS:
            d = DN18_TRANSLATIONS[p_idx]
            row['title'] = d['title']
            row['text'] = d['text']
            row['verse'] = d['verse']
            row['source'] = 'vri'
            row['translator'] = 'VRI Team'
            row['conf'] = 1.0
            count += 1
            
    with open(jsonl_path, 'w', encoding='utf-8') as f:
        for row in lines:
            f.write(json.dumps(row, ensure_ascii=False) + '\n')
    print(f"Patched {count} rows in {jsonl_path}")

