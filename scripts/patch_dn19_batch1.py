def patch_batch1():
    print("Patching db/text.db...")
    conn = sqlite3.connect('db/text.db')
    c = conn.cursor()
    for para_idx, data in translations.items():
        c.execute("""
            UPDATE translation 
            SET text = ?, title = ?, verse = ? 
            WHERE book_id = 6 AND para_idx = ?
        """, (data['text'], data['title'], data['verse'], para_idx))
    conn.commit()
    conn.close()
    print("db/text.db patched.")

    print("Patching web/public/books/6-trans.json...")
    json_path = 'web/public/books/6-trans.json'
    with open(json_path, 'r', encoding='utf-8') as f:
        web_data = json.load(f)
    
    for para_idx, data in translations.items():
        if para_idx < len(web_data):
            web_data[para_idx]['t'] = data['text']
            web_data[para_idx]['title'] = data['title']
            web_data[para_idx]['v'] = data['verse']
    
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(web_data, f, ensure_ascii=False, indent=2)
    print("web/public/books/6-trans.json patched.")

    print("Batch 1 successfully applied!")

if __name__ == '__main__':
    patch_batch1()
