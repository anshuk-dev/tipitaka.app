def update_jsonl():
    os.makedirs(os.path.dirname(TARGET_FILE), exist_ok=True)
    existing_map = {}
    if os.path.exists(TARGET_FILE):
        with open(TARGET_FILE, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        rec = json.loads(line)
                        existing_map[rec["para"]] = rec
                    except Exception:
                        pass

    for item in records:
        if len(item) == 4:
            para_idx, title, text, verse = item
        else:
            para_idx, title, text = item
            verse = None
        record = {
            "id": f"{BOOK_ID}-{para_idx}-hi",
            "book": BOOK_ID,
            "book_id": BOOK_ID,
            "para": para_idx,
            "para_idx": para_idx,
            "lang": "hi",
            "title": title,
            "text": text,
            "source": "विपश्यना विशोधन विन्यास (VRI) / सत्यानुभूति परम्परा",
            "translator": "Antigravity VRI AI Engine",
            "conf": 1
        }
        if verse:
            record["verse"] = verse
        existing_map[para_idx] = record

    sorted_paras = sorted(existing_map.keys())
    with open(TARGET_FILE, "w", encoding="utf-8") as f:
        for p in sorted_paras:
            f.write(json.dumps(existing_map[p], ensure_ascii=False) + "\n")

    print(f"Successfully updated {TARGET_FILE} with {len(sorted_paras)} records (range {sorted_paras[0]} to {sorted_paras[-1]}).")

