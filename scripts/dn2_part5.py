def clean_pali(text):
    text = re.sub(r'\|[MVPT][\d.]+\|', '', text)
    text = re.sub(r'\{.*?\}', '', text)
    text = re.sub(r'\*\*(.*?)\*\*', r'\1', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

